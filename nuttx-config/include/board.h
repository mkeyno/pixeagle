/* ==================== SPI SPEEDS ==================== */
/* Based on diagnostic results:
 * PCLK for SPI1/2/3 = 192 MHz (PLL1Q)
 * PCLK for SPI4 = 100 MHz (PLL2R)
 *
 * SPI1 (BMI088):
 *   - PCLK/64 = 192/64 = 3 MHz (safe, tested)
 *   - PCLK/32 = 192/32 = 6 MHz (tested OK)
 *   - PCLK/16 = 192/16 = 12 MHz (tested OK)
 *
 * SPI2 (FRAM):
 *   - PCLK/256 = 192/256 = ~750 kHz (SAFEST for FRAM)
 *   - PCLK/128 = 192/128 = 1.5 MHz (tested OK)
 *   - Mode 0 ONLY! (critical)
 *
 * SPI2 (SD Card):
 *   - Init: 400 kHz (requires PCLK/512 or software delay)
 *   - Normal: 12-25 MHz after init
 *
 * SPI4 (ICM-42688-P):
 *   - PCLK/16 = 100/16 = 6.25 MHz (tested OK)
 *   - PCLK/8 = 100/8 = 12.5 MHz (tested OK)
 *   - All modes work (using Mode 0)
 *
 *
SPI1 (BMI088):

Mode 0 or Mode 1 works
Speed: PCLK/16 to PCLK/256 all work
Recommendation: Mode 3, PCLK/64 (most common for Bosch sensors)

SPI2 (FRAM):

Mode 0 ONLY (CPOL=0, CPHA=0)
Device ID: 0x7F 7F 7F 7F (FM25V01A confirmed)
Speed: Works at all speeds, but 1MHz (PCLK/256) safest
Write-Read test PASSED ✓

SPI4 (ICM-42688-P):

All modes work (very flexible sensor)
Speed: PCLK/4 to PCLK/256 all work
Recommendation: Mode 0 or 3, PCLK/16
 *
 *
 */


