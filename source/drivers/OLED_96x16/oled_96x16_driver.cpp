int OLED_96x16::init()
{
	int ret = I2C::init();
	if (ret != PX4_OK) {
	return ret;
	}
	px4_usleep(100000);
	send_command(0xAE); // Display off
	send_command(0xD5); send_command(0x80); // Clock div
	send_command(0xA8); send_command(0x0F); // Mux ratio
	send_command(0xD3); send_command(0x00); // Display offset
	send_command(0x40); // Start line
	send_command(0x8D); send_command(0x14); // Charge pump
	send_command(0x20); send_command(0x02); // Page addressing mode
	send_command(0xA1); // Segment remap
	send_command(0xC8); // COM output scan direction
	send_command(0xDA); send_command(0x02); // COM pins
	send_command(0x81); send_command(0xCF); // Contrast
	send_command(0xD9); send_command(0xF1); // Pre-charge
	send_command(0xDB); send_command(0x40); // VCOMH
	send_command(0xA4); // Resume RAM content
	send_command(0xA6); // Normal display
	send_command(0xAF); // Display on
	clear();
	_initialized = true;
	return PX4_OK;
}
int OLED_96x16::send_command(uint8_t cmd)
{
	uint8_t data[2] = {0x00, cmd};
	return transfer(data, 2, nullptr, 0);
}
int OLED_96x16::send_data(const uint8_t *data, size_t len){
	const size_t chunk = 32;
	for (size_t i = 0; i < len; i += chunk) {
											size_t size = (len - i < chunk) ? (len - i) : chunk;
											uint8_t buf[1 + size];
											buf[0] = 0x40;
											memcpy(buf + 1, data + i, size);
											if (transfer(buf, 1 + size, nullptr, 0) != PX4_OK) {
																				return PX4_ERROR;
																				}
											}
	return PX4_OK;
}
void OLED_96x16::clear()
{
if (!_initialized) return;
memset(_buffer, 0, OLED_BUFFER_SIZE);
update();
}
void OLED_96x16::update()
{
if (!_initialized) return;
for (uint8_t page = 0; page < OLED_PAGES; page++) {
send_command(0xB0 + page);                    // Set page
send_command(0x00 + (DISPLAY_OFFSET & 0x0F));  // Low column
send_command(0x10 + ((DISPLAY_OFFSET >> 4) & 0x0F)); // High column
uint8_t rowData[OLED_TOTAL_WIDTH];
for (uint8_t c = 0; c < OLED_TOTAL_WIDTH; c++) {
rowData[c] = _buffer[c * OLED_PAGES + page];
}
send_data(rowData, OLED_TOTAL_WIDTH);
}
}
void OLED_96x16::print(const char *text, uint8_t x, uint8_t y)
{
if (!_initialized || (y != 0 && y != 8)) return;
uint8_t page = y / 8;
// Clear line
for (uint8_t col = 0; col < OLED_VISIBLE_WIDTH; col++) {
_buffer[col * OLED_PAGES + page] = 0;
}
uint8_t cursorX = x;
while (*text && cursorX <= OLED_VISIBLE_WIDTH - 6) {
uint8_t c = *text++;
if (c < 32 || c > 126) continue;
uint8_t idx = c - 32;
for (uint8_t col = 0; col < 5; col++) {
if (cursorX + col >= OLED_VISIBLE_WIDTH) break;
_buffer[(cursorX + col) * OLED_PAGES + page] = charMap[idx][col];
}
cursorX += 6;
}
update();
}
void OLED_96x16::print_two_lines(const char *line1, const char *line2)
{
clear();
if (line1) print(line1, 0, 0);
if (line2) print(line2, 0, 8);
}
void OLED_96x16::print_auto_wrap(const char *text)
{
clear();
char line1[17] = {0};
char line2[17] = {0};
size_t len = strlen(text);
if (len > 32) len = 32;
if (len <= 16)
strncpy(line1, text, 16);
else {
strncpy(line1, text, 16);
strncpy(line2, text + 16, len - 16);
}
print_two_lines(line1, line2);
}
void OLED_96x16::print_large(const char *text)
{
clear();
uint8_t len = strlen(text);
if (len > 8) len = 8;
const uint8_t charWidth = 12;
uint8_t totalWidth = len * charWidth;
uint8_t startX = (totalWidth < OLED_VISIBLE_WIDTH) ? (OLED_VISIBLE_WIDTH - totalWidth) / 2 : 0;
uint8_t cursorX = startX;
for (uint8_t i = 0; i < len; i++) {
draw_large_char(text[i], cursorX);
cursorX += charWidth;
}
update();
}
void OLED_96x16::draw_large_char(char c, uint8_t x)
{
if (c < 32 || c > 126) return;
uint8_t charIndex = c - 32;
for (uint8_t srcCol = 0; srcCol < 5; srcCol++) {
uint8_t srcByte = charMap[charIndex][srcCol];
uint8_t destCol1 = x + srcCol * 2;
uint8_t destCol2 = x + srcCol * 2 + 1;
if (destCol1 >= OLED_VISIBLE_WIDTH) break;
for (uint8_t srcRow = 0; srcRow < 8; srcRow++) {
if (!(srcByte & (1 << srcRow))) continue;
for (uint8_t scale = 0; scale < 2; scale++) {
uint8_t destRow = srcRow * 2 + scale;
uint8_t page = destRow / 8;
uint8_t bit = destRow % 8;
if (destCol1 < OLED_VISIBLE_WIDTH)
_buffer[destCol1 * OLED_PAGES + page] |= (1 << bit);
if (destCol2 < OLED_VISIBLE_WIDTH)
_buffer[destCol2 * OLED_PAGES + page] |= (1 << bit);
}
}
}
}
void OLED_96x16::draw_large_icon(uint8_t x, uint8_t icon_index)
{
// We draw a full 36x16 block, clearing and setting pixels properly
for (uint8_t destCol = x; destCol < x + 36 && destCol < OLED_VISIBLE_WIDTH; destCol++) {
uint8_t srcCol = (destCol - x) / 4;  // 36px / 8 = ~4.5 → use integer division
if (srcCol >= 8) srcCol = 7;
uint8_t srcByte = icons_8x8[icon_index][srcCol];
for (uint8_t srcRow = 0; srcRow < 8; srcRow++) {
uint8_t pixelOn = (srcByte & (1 << srcRow));
for (uint8_t vScale = 0; vScale < 2; vScale++) {
uint8_t destRow = srcRow * 2 + vScale;
uint8_t page = destRow / 8;
uint8_t bit = destRow % 8;
if (pixelOn) {
_buffer[destCol * OLED_PAGES + page] |= (1 << bit);
} else {
// Explicitly clear — critical for no ghosting!
_buffer[destCol * OLED_PAGES + page] &= ~(1 << bit);
}
}
}
}
}
void OLED_96x16::draw_icon_large(const char *text, uint8_t icon_index, uint8_t direction)
{
	if (direction != ICON_LEFT && direction != ICON_RIGHT) {
	direction = ICON_LEFT;
	}
	clear();  // Full clear → no ghosting ever
	// Safe icon index clamping
	if (icon_index >= sizeof(icons_8x8) / sizeof(icons_8x8[0])) {
	icon_index = 0;
	}
	uint8_t textLen = strlen(text);
	if (textLen > 5) textLen = 5;
	const uint8_t largeCharWidth = 12;
	const uint8_t iconScaledWidth = 36;  // 3 large chars equivalent
	uint8_t textWidth = textLen * largeCharWidth;
	uint8_t totalWidth = iconScaledWidth + textWidth + 6;  // + small gap
	uint8_t startX = (totalWidth < OLED_VISIBLE_WIDTH) ? (OLED_VISIBLE_WIDTH - totalWidth) / 2 : 0;
	uint8_t iconX = (direction == ICON_LEFT) ? startX : startX + textWidth + 6;
	uint8_t textX = (direction == ICON_LEFT) ? startX + iconScaledWidth + 6 : startX;
	// Draw large scaled icon
	draw_large_icon(iconX, icon_index);
	// Draw large text
	uint8_t cursorX = textX;
	for (uint8_t i = 0; i < textLen; i++) {
	draw_large_char(text[i], cursorX);
	cursorX += largeCharWidth;
	}
	update();
}
void OLED_96x16::draw_pixel(uint8_t x, uint8_t y)
{
	if (x >= OLED_VISIBLE_WIDTH || y >= OLED_HEIGHT) return;
	uint8_t page = y / 8;
	uint8_t bit = y % 8;
	_buffer[x * OLED_PAGES + page] |= (1 << bit);
}
void OLED_96x16::clear_pixel(uint8_t x, uint8_t y)
{
	if (x >= OLED_VISIBLE_WIDTH || y >= OLED_HEIGHT) return;
	uint8_t page = y / 8;
	uint8_t bit = y % 8;
	_buffer[x * OLED_PAGES + page] &= ~(1 << bit);
}
